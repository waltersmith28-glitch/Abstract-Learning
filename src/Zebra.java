public class Zebra {
    public int numLegs;
    public int numEyes;

    public Zebra(){
        numLegs = 4;
        numEyes = 2;
    }
    public int getNumLegs(){
        return numLegs;
    }
    public void setNumLegs(int numLegs){
        this.numLegs = numLegs;
    }
    public int getnumEyes(){
        return numEyes;
    }

    public void setNumEyes(int numEyes){
        this.numEyes = numEyes;
    }
}
